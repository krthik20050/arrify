(function () {
  'use strict';
  const key = 'stickitup-taste-v1';
  const mount = document.querySelector('#taste-discovery');
  const feed = document.querySelector('#personal-feed');
  const feedStatus = document.querySelector('#feed-status');
  const reduced = matchMedia('(prefers-reduced-motion: reduce)');
  let history = [], deck = [], loading = false, generation = 0, drag = null;
  try {
    const saved = JSON.parse(localStorage.getItem(key) || '[]');
    if (Array.isArray(saved)) history = saved.filter(x => x && (typeof x.id === 'string' || typeof x.id === 'number') && ['like', 'pass'].includes(x.decision)).slice(-300);
  } catch { /* An unavailable store does not prevent discovery. */ }
  let card, status, details, like, pass, undo, reset;
  const element = (tag, text, className) => {
    const node = document.createElement(tag);
    if (text !== undefined) node.textContent = text;
    if (className) node.className = className;
    return node;
  };
  function persist() {
    try { localStorage.setItem(key, JSON.stringify(history)); }
    catch { if (status) status.textContent = 'Your picks are saved for this visit. Browser storage is unavailable.'; }
  }
  async function request(events) {
    const response = await fetch('/api/discover', { method: 'POST', headers: { 'Content-Type': 'application/json' }, signal: AbortSignal.timeout(15000), body: JSON.stringify({ history: events }) });
    if (!response.ok) throw new Error('Discovery is temporarily unavailable.');
    return response.json();
  }
  function setBusy(value) {
    loading = value;
    if (!mount) return;
    mount.setAttribute('aria-busy', String(value));
    like.disabled = pass.disabled = value || !deck.length;
    undo.disabled = value || !history.length;
    reset.disabled = value || !history.length;
  }
  function renderCard() {
    if (!mount) return;
    card.replaceChildren();
    card.style.transform = '';
    card.style.transition = '';
    const product = deck[0];
    if (!product) {
      card.append(element('p', 'You have seen this selection. View your feed or reset to explore again.'));
      details.textContent = '';
      setBusy(false);
      return;
    }
    const image = element('img');
    image.alt = String(product.title || 'Sticker');
    image.src = /^https?:\/\//i.test(product.image) || String(product.image).startsWith('/') ? product.image : '/placeholder.svg';
    image.draggable = false;
    image.style.cssText = 'width:100%;height:100%;max-height:320px;object-fit:contain;pointer-events:none';
    image.addEventListener('error', () => { if (!image.src.endsWith('/placeholder.svg')) image.src = '/placeholder.svg'; });
    card.append(image);
    const link = element('a', product.title);
    link.href = '/products/' + encodeURIComponent(product.handle);
    const price = element('span', 'Rs. ' + Number(product.price || 0).toLocaleString('en-IN', { maximumFractionDigits: 2 }));
    details.replaceChildren(link, document.createTextNode(' · '), price);
    setBusy(false);
  }
  async function refreshDeck(message) {
    const current = ++generation;
    setBusy(true);
    if (status) status.textContent = message || 'Finding your next sticker…';
    try {
      const data = await request(history);
      if (current !== generation) return;
      deck = Array.isArray(data.deck) ? data.deck : [];
      renderCard();
      if (status) status.textContent = `${history.length} picks saved.${data.themes?.length ? ' Leaning toward ' + data.themes.join(', ') + '.' : ' Like a few designs to shape your feed.'}`;
    } catch (error) {
      if (current !== generation) return;
      deck = [];
      renderCard();
      status.replaceChildren(element('span', error.message + ' '));
      const retry = element('button', 'Try again', 'taste-retry');
      retry.type = 'button';
      retry.addEventListener('click', () => refreshDeck());
      status.append(retry);
    } finally { if (current === generation) setBusy(false); }
  }
  function decide(decision) {
    if (loading || !deck[0]) return;
    history.push({ id: deck[0].id, decision });
    history = history.slice(-300);
    persist();
    refreshDeck(decision === 'like' ? 'Liked. Finding your next sticker…' : 'Passed. Finding your next sticker…');
  }
  async function updateFeed(mode) {
    if (!feed) return;
    const token = String(Date.now()) + Math.random();
    feed.dataset.request = token;
    feed.setAttribute('aria-busy', 'true');
    if (feedStatus) feedStatus.textContent = 'Loading stickers…';
    try {
      const data = await request(mode === 'popular' ? [] : history);
      if (feed.dataset.request !== token) return;
      // This HTML is generated by the same-origin product renderer, never from user-entered markup.
      feed.innerHTML = data.feedHtml || '';
      const heading=document.querySelector('#feed-title');if(heading)heading.textContent=mode==='popular'?'Bestsellers':'Picked for you';
      if (feedStatus) feedStatus.textContent = mode === 'popular' ? 'Popular picks from across the store.' : history.length ? 'Selected from your likes, with new designs to explore.' : 'Like a few stickers to personalize these picks.';
      document.querySelectorAll('[data-feed]').forEach(button => {
        const active = button.dataset.feed === mode || (mode === 'personal' && button.dataset.feed === 'for-you');
        button.setAttribute('aria-pressed', String(active));
        button.classList.toggle('active', active);
      });
    } catch {
      if (feed.dataset.request === token && feedStatus) {
        feedStatus.replaceChildren(element('span', 'Could not refresh your feed. '));
        const retry = element('button', 'Try again');
        retry.type = 'button'; retry.addEventListener('click', () => updateFeed(mode)); feedStatus.append(retry);
      }
    } finally { if (feed.dataset.request === token) feed.setAttribute('aria-busy', 'false'); }
  }
  if (mount) {
    mount.replaceChildren();
    card = element('div', undefined, 'taste-card');
    card.tabIndex = 0;
    card.setAttribute('role', 'group');
    card.setAttribute('aria-label', 'Sticker discovery. Left arrow to pass, right arrow to like.');
    card.style.cssText = 'touch-action:pan-y;user-select:none;min-height:220px;display:flex;align-items:center;justify-content:center';
    details = element('p', undefined, 'taste-product');
    status = element('p', 'Loading stickers…', 'taste-status');
    status.setAttribute('role', 'status'); status.setAttribute('aria-live', 'polite');
    const actions = element('div', undefined, 'taste-actions');
    const button = (text, fn) => { const b = element('button', text); b.type = 'button'; b.style.minHeight = '44px'; b.style.minWidth = '64px'; b.addEventListener('click', fn); actions.append(b); return b; };
    pass = button('Pass', () => decide('pass'));
    like = button('Like', () => decide('like'));
    undo = button('Undo', () => { if (loading || !history.length) return; history.pop(); persist(); refreshDeck('Last pick undone.'); });
    reset = button('Reset', () => { history = []; persist(); refreshDeck('Picks reset.'); if (feed) updateFeed('popular'); });
    const see = element('a', 'See my feed', 'taste-feed-link'); see.href = '/?feed=for-you#your-feed';
    mount.append(card, details, actions, see, status);
    card.addEventListener('keydown', event => {
      if (event.target !== card || event.altKey || event.ctrlKey || event.metaKey) return;
      if (event.key === 'ArrowLeft' || event.key === 'ArrowRight') { event.preventDefault(); decide(event.key === 'ArrowRight' ? 'like' : 'pass'); }
    });
    card.addEventListener('pointerdown', event => {
      if (loading || !deck.length || !event.isPrimary || (event.pointerType === 'mouse' && event.button !== 0)) return;
      drag = { id: event.pointerId, x: event.clientX, y: event.clientY, dx: 0, horizontal: false };
    });
    card.addEventListener('pointermove', event => {
      if (!drag || drag.id !== event.pointerId) return;
      const dx = event.clientX - drag.x, dy = event.clientY - drag.y;
      if (!drag.horizontal) {
        if (Math.abs(dy) > 10 && Math.abs(dy) >= Math.abs(dx)) { drag = null; return; }
        if (Math.abs(dx) < 10 || Math.abs(dx) <= Math.abs(dy) * 1.3) return;
        drag.horizontal = true; card.setPointerCapture(event.pointerId);
      }
      drag.dx = dx;
      card.style.transition = 'none';
      card.style.transform = reduced.matches ? '' : `translateX(${dx}px) rotate(${Math.max(-6, Math.min(6, dx / 25))}deg)`;
      card.dataset.direction = dx > 0 ? 'like' : 'pass';
    });
    function release(event, cancel) {
      if (!drag || drag.id !== event.pointerId) return;
      const previous = drag; drag = null;
      if (card.hasPointerCapture(event.pointerId)) card.releasePointerCapture(event.pointerId);
      delete card.dataset.direction;
      card.style.transition = reduced.matches ? 'none' : 'transform 160ms cubic-bezier(.25,1,.5,1)';
      card.style.transform = '';
      if (!cancel && previous.horizontal && Math.abs(previous.dx) >= Math.min(100, card.clientWidth * .25)) decide(previous.dx > 0 ? 'like' : 'pass');
    }
    card.addEventListener('pointerup', event => release(event, false));
    card.addEventListener('pointercancel', event => release(event, true));
    refreshDeck();
  }
  document.querySelectorAll('[data-feed]').forEach(button => button.addEventListener('click', event => { event.preventDefault(); updateFeed(button.dataset.feed === 'popular' ? 'popular' : 'personal'); }));
  if (feed && (history.length || new URLSearchParams(location.search).get('feed') === 'for-you')) updateFeed('personal');
})();
